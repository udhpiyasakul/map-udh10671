export const UDH_CAMPUS_CENTER = {
  lat: 17.4158,
  lng: 102.7798,
};

// Coordinate conversion helper: lat/lng to 3D world meters relative to center
export function geoToWorldMeters(lat: number, lng: number): { x: number; z: number } {
  const LAT_METERS = 111132;
  const LNG_METERS = 106000;
  const x = (lng - UDH_CAMPUS_CENTER.lng) * LNG_METERS;
  const z = -(lat - UDH_CAMPUS_CENTER.lat) * LAT_METERS;
  return { x: Math.round(x * 10) / 10, z: Math.round(z * 10) / 10 };
}

